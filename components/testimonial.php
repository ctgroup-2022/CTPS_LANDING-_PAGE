document.addEventListener('DOMContentLoaded', function() {
    // Set animation delay for cards
    const cards = document.querySelectorAll('.testimonial-card1');
    cards.forEach((card, index) => {
        card.style.setProperty('--card-index', index);
    });
    
    // Auto slider setup
    setupAutoSlider();
    
    // Truncate long testimonials
    truncateTestimonials();
});

    // Auto slider functionality
    function setupAutoSlider() {
        const slider = document.querySelector('.slider1');
        const slides = document.querySelectorAll('.slide1');
        const sliderContainer = document.getElementById('auto-slider');
        
        let currentSlide = 0;
        let slideInterval;
        const slideDuration = 2000; // Changed from 5000 to 2000 (2 seconds per slide)
        
        // Function to go to a specific slide - UPDATED to move multiple cards
        function goToSlide(index) {
            const totalSlides = slides.length;
            
            // Determine how many slides to show/move based on viewport width
            let visibleSlides = 1;
            let slideWidth = 100; // Default 100% for mobile (1 card)
            
            if (window.innerWidth > 992) {
                visibleSlides = 3; // Desktop: always show 3 cards
                slideWidth = 33.333;
            } else if (window.innerWidth > 480) {
                visibleSlides = 2; // Tablet: show 2 cards
                slideWidth = 50;
            }
            
            // Calculate the maximum index we can start from
            const maxStartIndex = totalSlides - visibleSlides;
            
            // Handle index overflow/underflow with proper looping
            if (index > maxStartIndex) {
                // If we're beyond the max index, loop back to beginning
                currentSlide = 0;
            } else if (index < 0) {
                // If we're before the first slide, go to max
                currentSlide = maxStartIndex;
            } else {
                currentSlide = index;
            }
            
            // Apply smooth transform animation to slide multiple cards
            slider.style.transition = 'transform 0.8s cubic-bezier(0.65, 0, 0.35, 1)';
            slider.style.transform = `translateX(-${currentSlide * slideWidth}%)`;
            
            // Highlight active slides
            slides.forEach((slide, idx) => {
                // Mark visible slides as active
                if (idx >= currentSlide && idx < currentSlide + visibleSlides) {
                    slide.classList.add('active');
                } else {
                    slide.classList.remove('active');
                }
            });
        }
        
        // Function to advance to next GROUP of slides
        function nextSlide() {
            // Determine step size based on viewport width
            let slidesToMove = 1; // Default mobile
            
            if (window.innerWidth > 992) {
                slidesToMove = 3; // Desktop: always move 3 cards
            } else if (window.innerWidth > 480) {
                slidesToMove = 2; // Tablet: move 2 cards
            }
            
            // Move forward by the number of visible slides
            goToSlide(currentSlide + slidesToMove);
        }
        
        // Start auto sliding
        function startSlider() {
            // Clear any existing interval
            if (slideInterval) {
                clearInterval(slideInterval);
            }
            
            // Set the interval for auto sliding
            slideInterval = setInterval(nextSlide, slideDuration);
        }
        
        // Function to pause the slider
        function pauseSlider() {
            clearInterval(slideInterval);
        }
        
        // Add touch support for mobile
        let touchStartX = 0;
        let touchEndX = 0;
        
        sliderContainer.addEventListener('touchstart', (e) => {
            touchStartX = e.changedTouches[0].screenX;
            pauseSlider();
        }, { passive: true });
        
        sliderContainer.addEventListener('touchend', (e) => {
            touchEndX = e.changedTouches[0].screenX;
            handleSwipe();
            startSlider();
        }, { passive: true });
        
        function handleSwipe() {
            const swipeThreshold = 50; // Minimum distance for a swipe
            
            if (touchStartX - touchEndX > swipeThreshold) {
                // Swiped left - next slide group
                nextSlide();
            } else if (touchEndX - touchStartX > swipeThreshold) {
                // Determine step size based on viewport width
                let slidesToMove = 1; // Default mobile
                
                if (window.innerWidth > 992) {
                    slidesToMove = 3; // Desktop: move 3 cards
                } else if (window.innerWidth > 480) {
                    slidesToMove = 2; // Tablet: move 2 cards
                }
                
                // Move backward by the number of visible slides
                goToSlide(currentSlide - slidesToMove);
            }
        }
        
        // Pause auto sliding when user hovers over the slider
        sliderContainer.addEventListener('mouseenter', pauseSlider);
        sliderContainer.addEventListener('mouseleave', startSlider);
        
        // Pause when page is not visible
        document.addEventListener('visibilitychange', () => {
            if (document.visibilityState === 'hidden') {
                pauseSlider();
            } else {
                startSlider();
            }
        });
        
        // Handle window resize - recalculate visible slides and position
        window.addEventListener('resize', () => {
            // Quick debounce
            clearTimeout(window.resizeTimer);
            window.resizeTimer = setTimeout(() => {
                goToSlide(currentSlide);
            }, 250);
        });
        
        // Initialize slider - go to first slide and start auto sliding
        goToSlide(0);
        startSlider();
    }

    // Add function to truncate long testimonials
    function truncateTestimonials() {
        const testimonialParagraphs = document.querySelectorAll('.quote-box1 p:not(:first-of-type)');
        testimonialParagraphs.forEach(p => {
            let text = p.textContent;
            if (text.length > 60) {
                p.textContent = text.substring(0, 60).trim() + '...';
            }
        });
    }
</script>

